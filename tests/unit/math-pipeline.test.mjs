import assert from 'node:assert/strict';
import { additions, blindProblem, compareReviews, context, extractJSON, formatBank } from '../../scripts/math-pipeline.mjs';
import { validateBank as validateArith } from '../../scripts/validate-math-arith.mjs';
import { validateBank as validateFactor } from '../../scripts/validate-math-factorization.mjs';

const { bank, catalog } = context('arith', 'order-of-operations', 'a');
const raw = 'Preamble {invalid}\n```json\n{"problems":[{"expression":"(12 + 8) * 3 - 20 / 4","word":null,"choices":[55,50,60,45],"answerIndex":0}]}\n```\nDone';
const generated = extractJSON(raw, 'problems');
const escaped = { problems: [{ text: 'brace } and "quote"' }] };
assert.deepEqual(extractJSON(`prefix ${JSON.stringify(escaped)} suffix`, 'problems'), escaped);
assert.throws(() => extractJSON('not JSON', 'problems'));
const added = additions('arith', 'order-of-operations', 'a', bank, generated, 1, '2026-09-27');
assert.equal(added[0].id, `arith-${String(Math.max(...bank.problems.map(p => Number(p.id.split('-').at(-1)))) + 1).padStart(3, '0')}`);
assert.equal(added[0].position, Math.max(...bank.problems.filter(p => p.item === 'order-of-operations' && p.setId === 'a').map(p => p.position)) + 1);
assert.equal(added[0].published, false);
assert.throws(() => additions('arith', 'order-of-operations', 'a', bank, generated, 2));
const combined = { ...bank, problems: [...bank.problems, ...added] };
validateArith(combined);
assert.deepEqual(JSON.parse(formatBank(combined)), combined);
assert.match(formatBank(combined), /"choices": \[55, 50, 60, 45\]/);
const tooShort = { ...added[0], expression: '1 + 2', choices: [3, 2, 1, 4] };
assert.throws(() => validateArith({ version: 1, problems: [tooShort] }), /does not fit/);
const comingSoon = { ...added[0], item: 'soon', setId: 'a' };
assert.throws(() => validateArith({ version: 1, problems: [comingSoon] }, [...catalog, { item: 'soon', id: 'a' }]), /coming soon/);
const practiceB = { ...added[0], setId: 'c' };
validateArith({ version: 1, problems: [practiceB] }, [...catalog, { ...catalog[0], id: 'c' }]);
assert.throws(() => validateArith({ version: 1, problems: [] }, [{ item: 'bad', id: 'a', rule: 'missing' }]));
assert.throws(() => validateFactor({ version: 1, problems: [] }, [{ item: 'bad', id: 'a', rule: 'missing' }]));
const word = bank.problems.find(p => p.word);
assert.deepEqual(Object.keys(blindProblem('arith', word)).sort(), ['choices', 'id', 'type', 'word']);
const factor = context('factorization', 'difference-of-squares', 'a').bank.problems.find(p => p.item === 'difference-of-squares');
const blind = blindProblem('factorization', factor);
assert.deepEqual(Object.keys(blind).sort(), ['choices', 'id', 'trinomial', 'type']);
assert.match(blind.trinomial, /^x\^2 - \d+$/);
const review = { id: factor.id, answer: blind.choices[factor.answerIndex], choiceIndex: factor.answerIndex, wordExpression: null, issues: [] };
assert.equal(compareReviews('factorization', [factor], { reviews: [review] })[0].matches, true);
assert.equal(compareReviews('factorization', [factor], { reviews: [{ ...review, answer: 'wrong' }] })[0].matches, false);
assert.throws(() => compareReviews('factorization', [factor], { reviews: [] }));
assert.throws(() => compareReviews('factorization', [factor], { reviews: [{ ...review, id: 'unknown' }] }));
assert.throws(() => compareReviews('factorization', [factor, factor], { reviews: [review, review] }));
const arithReview = { id: word.id, answer: word.choices[word.answerIndex], choiceIndex: word.answerIndex, wordExpression: null, issues: [] };
assert.equal(compareReviews('arith', [word], { reviews: [arithReview] })[0].issues.length, 1);
assert.equal(compareReviews('arith', [word], { reviews: [{ ...arithReview, wordExpression: '1 + 2', issues: ['条件が曖昧'] }] })[0].issues.length, 1);
console.log('PASS: pipeline JSON extraction, numbering, formatting, shared rules, blind payloads and review comparison');
